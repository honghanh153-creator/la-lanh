"""Export Lá's static lines (content matrix) for the web client.

The API owns the catalog (``app/domains/readings/companion.py``); the client renders the
greetings, loading lines and mood reactions without a round-trip. Run after changing the
catalog; ``--check`` fails when the generated file is stale (used by tests and CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app.domains.readings.companion import (
    COMPANION_FALLBACK,
    COMPANION_GREETINGS,
    COMPANION_LOADING,
    COMPANION_MOOD_NUDGE,
    COMPANION_MOOD_REACTIONS,
    COMPANION_VOICE_VERSION,
    DAY_PARTS,
)

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
OUTPUT = (
    REPOSITORY_ROOT / "apps" / "web" / "src" / "shared" / "ui" / "la" / "laCatalog.generated.ts"
)


def _literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def render() -> str:
    greetings = {
        voice: {part: getattr(COMPANION_GREETINGS[part], voice) for part in DAY_PARTS}
        for voice in ("direct", "roast")
    }
    loading = {
        voice: [getattr(line, voice) for line in COMPANION_LOADING] for voice in ("direct", "roast")
    }
    moods = {
        voice: {mood.value: getattr(line, voice) for mood, line in COMPANION_MOOD_REACTIONS.items()}
        for voice in ("direct", "roast")
    }
    fallback = {"direct": COMPANION_FALLBACK.line.direct, "roast": COMPANION_FALLBACK.line.roast}
    return (
        "// Generated by `pnpm content:companion`"
        " (scripts/export_companion_catalog.py).\n"
        "// Source of truth: apps/api/app/domains/readings/companion.py"
        " (content matrix). Do not edit.\n\n"
        f"export const LA_CATALOG_VERSION = {_literal(COMPANION_VOICE_VERSION)};\n\n"
        f"export const LA_GREETINGS = {_literal(greetings)} as const;\n\n"
        f"export const LA_LOADING = {_literal(loading)} as const;\n\n"
        f"export const LA_MOOD_REACTIONS = {_literal(moods)} as const;\n\n"
        f"export const LA_MOOD_NUDGE = {_literal(COMPANION_MOOD_NUDGE)};\n\n"
        f"export const LA_NOTE_FALLBACK = {_literal(fallback)} as const;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT} is stale; run scripts.export_companion_catalog", file=sys.stderr)
            return 1
        print("Companion catalog export is current.")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
